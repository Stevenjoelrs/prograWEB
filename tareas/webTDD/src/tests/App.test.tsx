import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import App from '../views/App'
import { InMemoryProjectRepository } from './fakes/InMemoryProjectRepository'
import { buildContentSlide, buildProject } from './factories/projectFactory'

async function openProject(name: string) {
  await userEvent.click(await screen.findByRole('button', { name, exact: true }))
}

describe('editor de presentaciones', () => {
  it('crea un proyecto, edita una diapositiva y recupera su contenido al reabrir', async () => {
    const repository = new InMemoryProjectRepository()
    const user = userEvent.setup()
    const first = render(<App repository={repository} />)
    await user.click(await screen.findByRole('button', { name: 'Nuevo proyecto' }))
    await user.type(screen.getByLabelText('Nombre del proyecto'), 'Mi presentación')
    await user.type(screen.getByLabelText('Autor'), 'Ada')
    await user.type(screen.getByLabelText('Tema'), 'Computación')
    await user.click(screen.getByRole('button', { name: 'Crear presentación' }))
    await user.click(await screen.findByRole('button', { name: 'Añadir diapositiva' }))
    const title = await screen.findByLabelText('Título de la diapositiva')
    await user.clear(title)
    await user.type(title, 'Primer tema')
    await user.type(screen.getByLabelText('Texto'), 'Contenido persistente')
    await user.selectOptions(screen.getByLabelText('Formato'), 'text-and-image')
    await user.type(screen.getByLabelText('URL de imagen'), 'https://example.com/photo.png')
    await user.type(screen.getByLabelText('Descripción de la imagen'), 'Un diagrama')
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    await screen.findByText('Cambios guardados')
    expect(repository.savedProjects.at(-1)?.slides[1]).toMatchObject({ title: 'Primer tema', body: 'Contenido persistente', layout: 'text-and-image', imageAlt: 'Un diagrama' })
    first.unmount()

    render(<App repository={repository} />)
    await openProject('Mi presentación')
    await user.click(screen.getByRole('button', { name: '2. Primer tema' }))
    expect(screen.getByLabelText('Texto')).toHaveValue('Contenido persistente')
  })

  it('conserva el borrador y permite reintentar si falla el guardado', async () => {
    const repository = new InMemoryProjectRepository()
    const project = buildProject({ name: 'Proyecto guardado' })
    repository.seed(project)
    const user = userEvent.setup()
    render(<App repository={repository} />)
    await openProject(project.name)
    await user.type(screen.getByLabelText('Título de la diapositiva'), ' editado')
    repository.saveError = new Error('Sin espacio')
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Sin espacio')
    expect(screen.getByLabelText('Título de la diapositiva')).toHaveValue(`${project.slides[0].title} editado`)
    expect(repository.savedProjects).toHaveLength(0)
    repository.saveError = null
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    await screen.findByText('Cambios guardados')
  })

  it('avisa antes de abandonar un borrador o cerrar la página', async () => {
    const repository = new InMemoryProjectRepository()
    const project = buildProject()
    project.slides.push(buildContentSlide({ title: 'Segundo' }))
    repository.seed(project)
    const confirm = jest.spyOn(window, 'confirm').mockReturnValue(false)
    const user = userEvent.setup()
    render(<App repository={repository} />)
    await openProject(project.name)
    await user.type(screen.getByLabelText('Título de la diapositiva'), ' editado')
    await user.click(screen.getByRole('button', { name: '2. Segundo' }))
    expect(confirm).toHaveBeenCalled()
    expect(screen.getByLabelText('Título de la diapositiva')).toHaveValue(`${project.slides[0].title} editado`)
    const beforeUnload = new Event('beforeunload', { cancelable: true })
    window.dispatchEvent(beforeUnload)
    expect(beforeUnload.defaultPrevented).toBe(true)
  })

  it('presenta las diapositivas, limita la navegación y sale con Escape', async () => {
    const repository = new InMemoryProjectRepository()
    const project = buildProject()
    project.slides.push(buildContentSlide({ title: 'Desarrollo' }))
    repository.seed(project)
    const user = userEvent.setup()
    render(<App repository={repository} />)
    await openProject(project.name)
    await user.click(screen.getByRole('button', { name: 'Presentar' }))
    const presentation = await screen.findByRole('region', { name: 'Presentación' })
    expect(screen.getByRole('button', { name: 'Anterior' })).toBeDisabled()
    fireEvent.keyDown(window, { key: 'ArrowRight' })
    expect(presentation).toHaveTextContent('Desarrollo')
    expect(screen.getByRole('button', { name: 'Siguiente' })).toBeDisabled()
    fireEvent.keyDown(window, { key: 'ArrowRight' })
    expect(presentation).toHaveTextContent('Desarrollo')
    fireEvent.keyDown(window, { key: 'Escape' })
    await screen.findByLabelText('Título de la diapositiva')
  })

  it('solicita pantalla completa y permite continuar si el navegador la rechaza', async () => {
    const repository = new InMemoryProjectRepository()
    const project = buildProject()
    repository.seed(project)
    const request = jest.fn().mockRejectedValue(new Error('No permitido'))
    Object.defineProperty(document.documentElement, 'requestFullscreen', { configurable: true, value: request })
    render(<App repository={repository} />)
    await openProject(project.name)
    await userEvent.click(screen.getByRole('button', { name: 'Presentar' }))
    await waitFor(() => expect(request).toHaveBeenCalledTimes(1))
    expect(await screen.findByRole('region', { name: 'Presentación' })).toBeInTheDocument()
    expect(await screen.findByText(/No se pudo activar la pantalla completa/)).toBeInTheDocument()
    Reflect.deleteProperty(document.documentElement, 'requestFullscreen')
  })

  it('confirma la eliminación de un proyecto con sus diapositivas', async () => {
    const repository = new InMemoryProjectRepository()
    const project = buildProject()
    repository.seed(project)
    const confirm = jest.spyOn(window, 'confirm').mockReturnValue(false)
    render(<App repository={repository} />)
    await openProject(project.name)
    await userEvent.click(screen.getByRole('button', { name: 'Eliminar proyecto' }))
    expect(repository.deletedIds).toEqual([])
    confirm.mockReturnValue(true)
    await userEvent.click(screen.getByRole('button', { name: 'Eliminar proyecto' }))
    await waitFor(() => expect(repository.deletedIds).toEqual([project.id]))
  })
})
